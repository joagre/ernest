%% Report §11.4: the documentation a compiled module carries, rendered as
%% CommonMark. `ern doc` writes a whole module page and the shell's
%% `:doc` one declaration of it (§11.2); both read the EEP 48 documentation
%% chunk of the `.erc` (§11.1), which is the only source: a page is never
%% rendered from a source file. A manual page is the same page in roff,
%% which libs/markdown writes from the CommonMark (Appendix G.2).
-module(ern_page).

-export([page/1, prelude_page/0, module_head/1, manual/1, prelude_manual/0, declaration/3,
         session_declaration/3, prelude_declaration/1, since/1, declared_since/2]).

-include_lib("typer/include/ern_types.hrl").

%% Report §11.4: the page of one compiled module, built from its
%% documentation chunk and the namespace in its interface chunk (§11.1).
-spec page(binary() | file:filename()) -> unicode:chardata().
page(Beam) ->
    {ok, #{interface := #interface{namespace = Namespace}}} = ern_interface:read(Beam),
    {ok, Docs} = ern_docs:read(Beam),
    Name = ern_namespace:text(Namespace),
    render(["Ernest module ", Name], Name ++ ".", Docs).

%% Report §9, §11.4: the prelude's page, from the documentation its table
%% carries. A prelude name is written without a module's name before it.
-spec prelude_page() -> unicode:chardata().
prelude_page() ->
    render("Ernest prelude", "", ern_prelude:docs()).

%% Report §11.2: a module's documentation as `:doc` shows it, the head of
%% its page: the title, the version, and the module's doc block. What the
%% module declares is `:browse`'s to list.
-spec module_head(binary() | file:filename()) -> unicode:chardata().
module_head(Beam) ->
    {ok, #{interface := #interface{namespace = Namespace}}} = ern_interface:read(Beam),
    {ok, {docs_v1, _, ernest, _, ModuleDoc, _, _}} = ern_docs:read(Beam),
    head(["Ernest module ", ern_namespace:text(Namespace)], ModuleDoc).

%% Report §11.4: the page of one compiled module as a manual page,
%% `Ernest.Net.Http` in section 3ern.
-spec manual(binary() | file:filename()) -> unicode:chardata().
manual(Beam) ->
    {ok, #{interface := #interface{namespace = Namespace}}} = ern_interface:read(Beam),
    {ok, Docs} = ern_docs:read(Beam),
    Name = ern_namespace:text(Namespace),
    roff("Ernest." ++ Name, ["Ernest module ", Name], Name ++ ".", Docs).

%% Report §9, §11.4: the prelude's page as a manual page, `Ernest.Prelude`.
-spec prelude_manual() -> unicode:chardata().
prelude_manual() ->
    roff("Ernest.Prelude", "Ernest prelude", "", ern_prelude:docs()).

render(Title, Prefix, {docs_v1, _, ernest, _, ModuleDoc, Meta, Entries}) ->
    [head(Title, ModuleDoc),
     [entry(Entry, Prefix) || Entry <- Entries],
     "---\n\n", generated(Meta), "\n"].

%% Report §11.4: the page after its title, under the manual page's header.
%% The NAME line is the first sentence of the module's doc block, its
%% `since` line apart, or the page's title where the block has no
%% paragraph, and the page's last line is a comment at the head of the
%% source. libs/markdown takes the header as a `Manual`, a named
%% constructor, whose fields stand in their declared order.
roff(Name, Title, Prefix, {docs_v1, _, ernest, _, ModuleDoc, Meta, Entries}) ->
    Body = [module_text(ModuleDoc), [entry(Entry, Prefix) || Entry <- Entries]],
    {Prose, _} = case ModuleDoc of
                     none -> {<<>>, undefined};
                     #{<<"en">> := DocText} -> split_since(DocText)
                 end,
    Summary = case 'ern@markdown':firstSentence(markdown(Prose)) of
                  [] -> 'ern@markdown':firstSentence(markdown(Title));
                  Sentence -> Sentence
              end,
    Manual = {'Manual', list_to_binary(Name), <<"3ern">>, Summary, <<"Ernest ", ?VERSION>>,
              <<"Ernest Manual">>},
    Lines = 'ern@markdown':roff(markdown(Body), Manual),
    [".\\\" ", generated(Meta), "\n", lists:join("\n", Lines), "\n"].

markdown(Text) ->
    'ern@markdown':parse(unicode:characters_to_binary(Text)).

%% The source's name is the chunk's own word, which a module from anywhere
%% may have written: its control characters are written as escapes, so
%% that none ends the comment line a manual page keeps it on. A page, and
%% a manual page's header, name the release whose library they document,
%% VERSION's text, without the mark of a build that is no release
%% (ern_release), since `make pages` writes the release's pages from the
%% repository's build (docs/release_review.md, step 5).
generated(Meta) ->
    Source = case maps:get(source, Meta, <<>>) of
                 Name when is_binary(Name) ->
                     case unicode:characters_to_binary(Name) of
                         Name -> ern_show:controls(Name, line);
                         _ -> <<>>
                     end;
                 _ ->
                     <<>>
             end,
    ["Generated by ern ", ?VERSION, " from ", Source, "."].

head(Title, ModuleDoc) ->
    ["# ", Title, "\n\n", module_text(ModuleDoc)].

module_text(none) ->
    [];
module_text(#{<<"en">> := DocText}) ->
    {Text, Since} = split_since(DocText),
    [since_line(Since), Text, "\n\n"].

entry({{_, Name, _}, _, Signature, Doc, Meta}, Prefix) ->
    section([Prefix, atom_to_list(Name)], Signature, Doc, Meta).

%% A declaration's section under its heading: its signature, its `since`
%% line, whether it is private (report §11.4), its text, and its items.
section(Heading, Signature, Doc, Meta) ->
    {Text, Since} = case Doc of
                        none -> {undefined, undefined};
                        #{<<"en">> := DocText} -> split_since(DocText)
                    end,
    ["## ", Heading, "\n\n```ernest\n",
     lists:join("\n", [binary_to_list(Line) || Line <- Signature]), "\n```\n\n",
     since_line(Since),
     case Meta of
         #{private := true} -> "*Private to the module.*\n\n";
         _ -> []
     end,
     case Text of
         undefined -> [];
         <<>> -> [];
         _ -> [Text, "\n\n"]
     end,
     items(Meta)].

%% The documented constructors and fields as a list.
items(#{items := Items}) -> list([item(Item) || Item <- Items]);
items(_) -> [].

item(#{kind := constructor, name := Name, doc := Doc, fields := Fields}) ->
    FieldItems = [["  - `", atom_to_list(Field), " : ", Type, "`: ", FieldDoc, "\n"]
                  || #{name := Field, type := Type, doc := FieldDoc} <- Fields, FieldDoc =/= none],
    case {Doc, FieldItems} of
        {none, []} -> [];
        {none, _} -> [["- `", atom_to_list(Name), "`\n"], FieldItems];
        _ -> [["- `", atom_to_list(Name), "`: ", Doc, "\n"], FieldItems]
    end.

list(Items) ->
    case lists:flatten(Items) of
        [] -> [];
        _ -> [Items, "\n"]
    end.

%% Appendix E.0 shape rule 6: a doc block's last line `since v` names the version
%% the declaration appeared in; it is rendered after the synopsis.
split_since(Doc) ->
    Lines = binary:split(string:trim(Doc, trailing), <<"\n">>, [global]),
    case lists:last(Lines) of
        <<"since ", Version/binary>> ->
            case is_version(Version) of
                true ->
                    Text = iolist_to_binary(lists:join(<<"\n">>, lists:droplast(Lines))),
                    {string:trim(Text, trailing), Version};
                false ->
                    {Doc, undefined}
            end;
        _ ->
            {Doc, undefined}
    end.

%% A version as a `since` line writes it: a digit, then digits, letters,
%% `.`, `+` and `-`.
is_version(<<First, Rest/binary>>) when First >= $0, First =< $9 ->
    lists:all(fun(Char) ->
                  (Char >= $0 andalso Char =< $9) orelse (Char >= $a andalso Char =< $z)
                      orelse (Char >= $A andalso Char =< $Z)
                      orelse Char =:= $. orelse Char =:= $+ orelse Char =:= $-
              end, binary_to_list(Rest));
is_version(_) ->
    false.

since_line(undefined) -> [];
since_line(Version) -> ["*Since ", Version, ".*\n\n"].

%% Report §11.2: one declaration's documentation, as `:doc` prints it. The
%% name is the unqualified one the entry carries, `map` or `Stack.push`, as
%% it is written, so that no name is made of what a person typed. The
%% signature is the one given, as the shell prints it, or with `entry` the
%% entry's own, in the module's names.
-spec declaration(binary() | file:filename(), binary(), [string()] | entry) ->
          {ok, unicode:chardata()} | none.
declaration(Beam, Name, Signature) ->
    {ok, #{interface := #interface{namespace = Namespace}}} = ern_interface:read(Beam),
    {ok, {docs_v1, _, ernest, _, _, _, Entries}} = ern_docs:read(Beam),
    Prefix = ern_namespace:text(Namespace) ++ ".",
    case find(Name, Entries) of
        {ok, Entry} when Signature =:= entry ->
            {ok, entry(Entry, Prefix)};
        {ok, {KindNameArity, Anno, _, Doc, Meta}} ->
            {ok, entry({KindNameArity, Anno, lines(Signature), Doc, Meta}, Prefix)};
        none ->
            none
    end.

%% The entry of a name as it is written.
find(Name, Entries) ->
    case [Entry || {{_, EntryName, _}, _, _, _, _} = Entry <- Entries,
                   atom_to_binary(EntryName) =:= Name] of
        [Entry | _] -> {ok, Entry};
        [] -> none
    end.

%% Report §11.2: a declaration the session made, under the name the session
%% writes and with the signature given, the type as the shell prints it,
%% since a value's entry is written under the input's namespace, which is
%% not the session's; `entry` keeps the entry's own, which a type's is.
%% A name with no entry, one a `let` at the prompt bound, is its name and
%% type alone.
-spec session_declaration(binary() | none, binary(), [string()] | entry) -> unicode:chardata().
session_declaration(Beam, Name, Signature) ->
    Entries = case Beam of
                  none ->
                      [];
                  _ ->
                      {ok, {docs_v1, _, ernest, _, _, _, Found}} = ern_docs:read(Beam),
                      Found
              end,
    case find(Name, Entries) of
        none ->
            section(Name, lines(Signature), none, #{});
        {ok, Entry} when Signature =:= entry ->
            entry(Entry, "");
        {ok, {KindNameArity, Anno, _, Doc, Meta}} ->
            entry({KindNameArity, Anno, lines(Signature), Doc, Meta}, "")
    end.

lines(Signature) -> [unicode:characters_to_binary(Line) || Line <- Signature].

%% Report §9, §11.2: one prelude name's documentation, `send`,
%% `Address.call`, or `Optional`, as `:doc` prints it.
-spec prelude_declaration(binary()) -> {ok, unicode:chardata()} | none.
prelude_declaration(Name) ->
    {docs_v1, _, ernest, _, _, _, Entries} = ern_prelude:docs(),
    case find(Name, Entries) of
        {ok, Entry} -> {ok, entry(Entry, "")};
        none -> none
    end.

%% Appendix E.0 shape rule 6: the version a module, or the prelude, appeared in,
%% which a declaration without a `since` of its own shares.
-spec since(binary() | file:filename() | prelude) -> binary() | undefined.
since(prelude) ->
    module_since(ern_prelude:docs());
since(Beam) ->
    {ok, Docs} = ern_docs:read(Beam),
    module_since(Docs).

%% Appendix E.0 shape rule 6: the `since` a declaration's own doc block ends
%% with, in a module or the prelude, or undefined for one that has none and
%% so has its module's.
-spec declared_since(binary() | prelude, binary()) -> binary() | undefined.
declared_since(Source, Name) ->
    {docs_v1, _, _, _, _, _, Entries} = case Source of
                                            prelude -> ern_prelude:docs();
                                            Beam -> element(2, ern_docs:read(Beam))
                                        end,
    case find(Name, Entries) of
        {ok, {_, _, _, #{<<"en">> := DocText}, _}} -> element(2, split_since(DocText));
        _ -> undefined
    end.

module_since({docs_v1, _, _, _, #{<<"en">> := DocText}, _, _}) ->
    {_, Since} = split_since(DocText),
    Since;
module_since(_) ->
    undefined.
