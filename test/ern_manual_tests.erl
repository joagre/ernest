%% The manual pages as `make manual` writes them, held to §11 and rendered.
%% Run from this directory by its Makefile, never beside ern_install_tests:
%% both write under ../build/stdlib, these tests by `ern doc --man`, by
%% `make manual` and `make doc`, and by a file of their own, and those by
%% make. The helpers that run a command and build are
%% ern_integration_tests'.
-module(ern_manual_tests).

-include_lib("eunit/include/eunit.hrl").
-include_lib("kernel/include/file.hrl").

%% report §11, §11.4: the manual pages `make manual` writes. `ern doc --man`
%% writes the prelude's page and each standard library module's beside its
%% .erc; tools/manual.ern writes ern(1), whose NAME line and DESCRIPTION
%% are §11's, its subsections §11.1 to §11.6 and those after §11.8, in
%% the report's order, whose SYNOPSIS is every job's usage as its `--help`
%% prints it, in `ern --help`'s order, then `ern --help` and `ern
%% --version`, whose
%% OPTIONS and EXIT STATUS are §11.7 and §11.8, and whose SEE ALSO names
%% those pages, the prelude's first. Every page renders without a warning:
%% groff checks it where it is installed, with UTF-8 read as man-db reads
%% it, mandoc where groff is not, and a machine with neither says so.
%% Written after the code, a regression test.
manual_pages_test_() ->
    {timeout, 120, fun manual_pages/0}.

manual_pages() ->
    _ = ern_integration_tests:succeed("../bin/ern doc --man --build-root ../build/stdlib "
                                      "../src/stdlib"),
    Modules = [filename:basename(File, ".ern")
               || File <- ern_repository:files(["src/stdlib/*.ern"])],
    Pages = ["../build/stdlib/Ernest." ++ ern_namespace:text(ern_namespace:namespace([Module]))
             ++ ".3ern" || Module <- Modules]
        ++ ["../build/stdlib/Ernest.Prelude.3ern"],
    ?assertEqual([], [Page || Page <- Pages, not filelib:is_regular(Page)]),
    0 = ern_integration_tests:build("--build-root build/tools ../tools"),
    Output = ern_integration_tests:succeed("../bin/ern run build/tools/manual.erc "
                                           "../report/toolchain.md 9.9.9 ../build/stdlib"),
    ok = file:write_file("build/ern.1", Output),
    Lines = binary:split(Output, <<"\n">>, [global, trim]),
    ?assertMatch([<<".\\\" Generated by tools/manual.ern from ../report/toolchain.md.">>,
                  <<".TH \"ern\" \"1\" \"\" \"Ernest 9.9.9\" \"Ernest Manual\"">>,
                  <<".nh">>, <<".ds AD l">>, <<".ad l">>,
                  <<".SH NAME">>, <<"ern \\- the Ernest toolchain">>,
                  <<".SH">>, <<"SYNOPSIS">>, <<".PP">> | _], Lines),
    Pairs = lists:zip(lists:droplast(Lines), tl(Lines)),
    %% man-pages(7)'s sections, in its order
    ?assertEqual([<<"SYNOPSIS">>, <<"DESCRIPTION">>, <<"OPTIONS">>, <<"EXIT STATUS">>,
                  <<"SEE ALSO">>],
                 [Section || {<<".SH">>, Section} <- Pairs]),
    [_, Synopsis | _] = binary:split(Output, [<<"SYNOPSIS">>, <<"DESCRIPTION">>], [global]),
    %% a regression test: `ern build` stood twice, a refusal of `ern
    %% config`'s stood as a usage, and `ern reload`, `ern stop` and `ern
    %% unpack` stood nowhere
    ?assertEqual([usage(Job) || Job <- jobs()] ++ [<<"ern --help">>, <<"ern --version">>],
                 [binary:replace(binary:part(Line, 3, byte_size(Line) - 6), <<"\\-">>, <<"-">>,
                                 [global])
                  || <<"\\fB", _/binary>> = Line <- binary:split(Synopsis, <<"\n">>, [global])]),
    ?assertMatch({_, _}, binary:match(Output, <<".SH\nDESCRIPTION\n.PP\n"
                                                "The toolchain is one command, \\fBern\\fR, ">>)),
    {ok, Report} = file:read_file("../report/toolchain.md"),
    {match, Sections} = re:run(Report, "^### (11\\.(?:[0-6]|9) .*)$",
                               [multiline, global, {capture, all_but_first, binary}]),
    Subsections = [binary:replace(Section, <<"`">>, <<>>, [global]) || [Section] <- Sections],
    ?assertEqual(Subsections, [Section || {<<".SS">>, Section} <- Pairs]),
    %% every subsection stands in DESCRIPTION, those after §11.8 among them
    Described = lists:takewhile(fun(Pair) -> Pair =/= {<<".SH">>, <<"OPTIONS">>} end, Pairs),
    ?assertEqual(Subsections, [Section || {<<".SS">>, Section} <- Described]),
    ?assertMatch({_, _}, binary:match(Output, <<".SH\nSEE ALSO\n.PP\n\\fBErnest.Prelude\\fR(3ern), "
                                                "\\fBErnest.Bool\\fR(3ern), ">>)),
    SeeAlso = fun(Module) ->
                  iolist_to_binary(["\\fBErnest.",
                                    ern_namespace:text(ern_namespace:namespace([Module])),
                                    "\\fR(3ern)"])
              end,
    ?assertEqual([], [Module || Module <- Modules,
                                binary:match(Output, SeeAlso(Module)) =:= nomatch]),
    rendered(["build/ern.1" | Pages]).

%% The jobs `ern --help` lists, in its order.
jobs() ->
    Help = ern_integration_tests:succeed("../bin/ern --help"),
    [_, Listed | _] = binary:split(Help, <<"\n\n">>, [global]),
    [hd(binary:split(Line, <<" ">>, [global, trim_all]))
     || Line <- binary:split(Listed, <<"\n">>, [global])].

%% A job's usage as its `--help` prints it, on one line.
usage(Job) ->
    Help = ern_integration_tests:succeed("../bin/ern " ++ binary_to_list(Job) ++ " --help"),
    [<<"Usage: ", Usage/binary>> | _] = binary:split(Help, <<"\n\n">>),
    iolist_to_binary(lists:join(<<" ">>, binary:split(Usage, [<<" ">>, <<"\n">>],
                                                      [global, trim_all]))).

%% report §11.4: make writes ern(1) as `ern doc` writes a page, only where
%% it is older than what it is made from, so `make manual` after a make,
%% which this target's make runs first, leaves it as it is: its time, and
%% its file, which a writing replaces whole. `make doc` runs between the
%% two and writes into build/stdlib, beside the pages, the document this
%% test removes first, which leaves ern(1) as it is too. ern(1)'s
%% prerequisites are the Makefile's rule: the tests below hold two of
%% them, the pages' names and the compiled libs/markdown, and none holds
%% the others.
manual_written_once_test_() ->
    {timeout, 120, fun manual_written_once/0}.

manual_written_once() ->
    {ok, #file_info{mtime = Written, inode = Inode}} =
        file:read_file_info("../build/man/ern.1", [{time, posix}]),
    _ = file:delete("../build/stdlib/bool.md"),
    _ = ern_integration_tests:succeed("make -s -C .. doc"),
    ?assert(filelib:is_regular("../build/stdlib/bool.md")),
    _ = ern_integration_tests:succeed("make -s -C .. manual"),
    ?assertMatch({ok, #file_info{mtime = Written, inode = Inode}},
                 file:read_file_info("../build/man/ern.1", [{time, posix}])).

%% report §11.4: ern(1)'s SEE ALSO names the pages in build/stdlib, so a
%% page added there makes the next `make manual` write ern(1) again with
%% its name, and the page removed makes the next write it again without.
%% The file added is no page of a module, which the sweep of `ern doc
%% --man` keeps. The test removes it whatever its assertions answer, and
%% makes ern(1) again.
%%
%% Written after the code, a regression test, which passes with the
%% directory build/stdlib as ern(1)'s prerequisite too. It does not cover a
%% page that `ern doc --man` removes itself, of a module whose source is
%% gone.
manual_names_pages_test_() ->
    {timeout, 120, fun manual_names_pages/0}.

manual_names_pages() ->
    Page = "../build/stdlib/Ernest.ManualTestPage.3ern",
    Named = <<"\\fBErnest.ManualTestPage\\fR(3ern)">>,
    try
        Before = written(),
        ok = file:write_file(Page, <<"no page of a module\n">>),
        _ = ern_integration_tests:succeed("make -s -C .. manual"),
        Added = written(),
        ?assertNotEqual(Before, Added),
        ?assertMatch({_, _}, binary:match(manual(), Named)),
        ok = file:delete(Page),
        _ = ern_integration_tests:succeed("make -s -C .. manual"),
        ?assertNotEqual(Added, written()),
        ?assertEqual(nomatch, binary:match(manual(), Named))
    after
        _ = file:delete(Page),
        _ = ern_integration_tests:succeed("make -s -C .. manual")
    end.

%% report §11.4: ern(1) is written where it is older than what it is made
%% from, the compiled libs/markdown that lays it out among it, so the
%% compiled libs/markdown made newer than ern(1) makes the next `make
%% manual` write ern(1) again. Its time alone is made newer, a nanosecond
%% past ern(1)'s, which is past already, so that no file's time is in the
%% future and nothing is written again for it after the test's make.
%%
%% It does not cover the toolchain's own code, which the same rule names:
%% a file of it made newer would have every later job in the run write its
%% pages again.
manual_follows_markdown_test_() ->
    {timeout, 120, fun manual_follows_markdown/0}.

manual_follows_markdown() ->
    Before = written(),
    _ = ern_integration_tests:succeed("touch -d @" ++ past("../build/man/ern.1")
                                      ++ " ../build/libs/markdown/markdown.erc"),
    _ = ern_integration_tests:succeed("make -s -C .. manual"),
    ?assertNotEqual(Before, written()).

%% The time a nanosecond past File's, as `touch -d @` reads one.
past(File) ->
    Stat = ern_integration_tests:succeed("stat -c %.9Y " ++ File, [{env, [{"LC_ALL", "C"}]}]),
    [Seconds, Fraction] = binary:split(string:trim(Stat), <<".">>),
    Past = binary_to_integer(Seconds) * 1000000000 + binary_to_integer(Fraction) + 1,
    lists:flatten(io_lib:format("~B.~9..0B", [Past div 1000000000, Past rem 1000000000])).

%% ern(1)'s time and its file, which a writing replaces whole.
written() ->
    {ok, #file_info{mtime = Time, inode = Inode}} =
        file:read_file_info("../build/man/ern.1", [{time, posix}]),
    {Time, Inode}.

manual() ->
    {ok, Manual} = file:read_file("../build/man/ern.1"),
    Manual.

rendered(Pages) ->
    case {os:find_executable("groff"), os:find_executable("mandoc")} of
        {false, false} ->
            io:format(user, "  groff and mandoc not installed; the manual pages' rendering "
                            "was not checked.~n", []);
        {false, _} ->
            ?assertEqual([], [{Page, Result}
                              || Page <- Pages,
                                 {Status, _} = Result <- [ern_integration_tests:sh(
                                                              "mandoc -Tlint -W error " ++ Page)],
                                 Status =/= 0]);
        _ ->
            ?assertEqual([], [{Page, Result}
                              || Page <- Pages,
                                 Result <- [ern_integration_tests:sh(
                                                "groff -k -man -Tutf8 -ww -z " ++ Page)],
                                 Result =/= {0, <<>>}])
    end.
